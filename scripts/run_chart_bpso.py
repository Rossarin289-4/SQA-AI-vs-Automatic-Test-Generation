#!/usr/bin/env python3
"""Run reproducible BPSO experiments for Defects4J Chart-1."""

import argparse
import csv
import json
import re
import shutil
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BPSO = ROOT / "Chart" / "BPSO"
INDEX = ROOT / "Chart" / "bug-index.csv"
SELECTOR = BPSO / "Code" / "BPSOTestSelector.java"
CANDIDATES = BPSO / "Configuration" / "chart-1-candidates.csv"
SOURCE = BPSO / "Test" / "Chart-1" / "org" / "jfree" / "chart" / "renderer" / "category" / "junit" / "Chart1BPSOCandidateTest.java"
PACKAGE = "org.jfree.chart.renderer.category.junit"
CLASS = "Chart1BPSOCandidateTest"
METHOD = re.compile(r"\bpublic\s+void\s+(test\w+)\s*\(")
FAILURES = re.compile(r"Failing tests:\s*(\d+)", re.I)
COVERAGE = re.compile(r"(?P<kind>line|condition)\s+coverage\s*:\s*(?P<covered>\d+)\s*/\s*(?P<total>\d+)", re.I)


def now():
    return datetime.now(timezone.utc).isoformat()


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(value, indent=2) + "\n", encoding="utf-8")
    temporary.replace(path)


def run(command, cwd, log, timeout):
    started = time.monotonic()
    try:
        result = subprocess.run(command, cwd=cwd, text=True, stdout=subprocess.PIPE,
                                stderr=subprocess.STDOUT, timeout=timeout, check=False)
        output, code = result.stdout, result.returncode
    except subprocess.TimeoutExpired as exc:
        output, code = (exc.stdout or "") + "\nTIMEOUT\n", 124
    log.parent.mkdir(parents=True, exist_ok=True)
    log.write_text("$ " + " ".join(map(str, command)) + "\n" + output, encoding="utf-8")
    return {"exit_code": code, "seconds": round(time.monotonic() - started, 3),
            "log": str(log.relative_to(ROOT)), "output": output}


def require(step, action):
    if step["exit_code"] != 0:
        raise RuntimeError(f"{action} failed; see {step['log']}")


def candidate_ids():
    with CANDIDATES.open(newline="", encoding="utf-8") as stream:
        rows = list(csv.DictReader(stream))
    ids = [row["test_id"].strip() for row in rows]
    methods = METHOD.findall(SOURCE.read_text(encoding="utf-8"))
    if not ids or len(ids) != len(set(ids)) or set(ids) != set(methods):
        raise ValueError("Candidate CSV IDs must exactly match public test methods")
    return ids


def compile_selector(output, timeout):
    build = output / "selector-build"
    step = run(["javac", "-d", str(build), str(SELECTOR)], ROOT,
               output / "compile-selector.log", timeout)
    require(step, "Compile selector")
    return build


def export(defects4j, checkout, property_name, output, timeout):
    step = run([defects4j, "export", "-p", property_name], checkout,
               output / f"export-{property_name}.log", timeout)
    require(step, f"Export {property_name}")
    lines = [line.strip() for line in step["output"].splitlines() if line.strip()]
    if not lines:
        raise RuntimeError(f"No Defects4J value for {property_name}")
    value = Path(lines[-1])
    return value if value.is_absolute() else checkout / value


def install_selected_suite(test_root, selected):
    package_path = test_root / Path(*PACKAGE.split("."))
    package_path.mkdir(parents=True, exist_ok=True)
    shutil.copy2(SOURCE, package_path / SOURCE.name)
    body = [f"package {PACKAGE};", "", "import junit.framework.TestCase;", "",
            "/** Generated by run_chart_bpso.py. */",
            "public final class Chart1BPSOSelectedSuite extends TestCase {",
            "    public void testSelectedCandidates() throws Throwable {"]
    body.extend(f"        new {CLASS}(\"{name}\").runBare();" for name in selected)
    body.extend(["    }", "}", ""])
    (package_path / "Chart1BPSOSelectedSuite.java").write_text("\n".join(body), encoding="utf-8")


def coverage_metrics(output):
    metrics = {}
    for match in COVERAGE.finditer(output):
        covered, total = int(match["covered"]), int(match["total"])
        metrics[match["kind"].lower()] = {"covered": covered, "total": total,
                                           "percent": round(100 * covered / total, 3) if total else None}
    return metrics or None


def execute_version(defects4j, suffix, selected, work_root, output, timeout):
    checkout = work_root / f"Chart-1{suffix}"
    label = "buggy" if suffix == "b" else "fixed"
    out = output / label
    if not (checkout / ".defects4j.config").is_file():
        if checkout.exists() and any(checkout.iterdir()):
            raise RuntimeError(f"{checkout} exists but is not a Defects4J checkout")
        checkout.parent.mkdir(parents=True, exist_ok=True)
        require(run([defects4j, "checkout", "-p", "Chart", "-v", f"1{suffix}", "-w", str(checkout)], ROOT,
                    out / "checkout.log", timeout), f"Checkout Chart-1{suffix}")
    require(run([defects4j, "compile"], checkout, out / "compile-before.log", timeout),
            f"Compile Chart-1{suffix}")
    install_selected_suite(export(defects4j, checkout, "dir.src.tests", out, timeout), selected)
    require(run([defects4j, "compile"], checkout, out / "compile-after.log", timeout),
            f"Compile selected tests Chart-1{suffix}")
    tests = []
    for number, method in enumerate(selected, 1):
        step = run([defects4j, "test", "-t", f"{PACKAGE}.{CLASS}::{method}"], checkout,
                   out / f"test-{number:03d}-{method}.log", timeout)
        match = FAILURES.search(step["output"])
        tests.append({"test": method, "failing_tests": int(match.group(1)) if match else None,
                      "execution": {key: value for key, value in step.items() if key != "output"}})
    suite = f"{PACKAGE}.Chart1BPSOSelectedSuite::testSelectedCandidates"
    step = run([defects4j, "coverage", "-t", suite], checkout, out / "coverage.log", timeout)
    return {"checkout": str(checkout), "tests": tests,
            "coverage": {"execution": {key: value for key, value in step.items() if key != "output"},
                         "metrics": coverage_metrics(step["output"])}}


def update_index(status):
    with INDEX.open(newline="", encoding="utf-8") as stream:
        rows, fields = list(csv.DictReader(stream)), stream.fieldnames
    for row in rows:
        if row["bug_id"] == "Chart-1":
            row["bpso"] = status
    temporary = INDEX.with_suffix(".tmp")
    with temporary.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)
    temporary.replace(INDEX)


def one_round(defects4j, build, seed, round_number, args, ids):
    output = BPSO / f"Result_Round{round_number}" / "Chart-1"
    summary_path = output / "summary.json"
    summary = {"schema_version": 1, "project": "Chart", "bug_id": "Chart-1", "round": round_number,
               "seed": seed, "status": "running", "started_utc": now()}
    write_json(summary_path, summary)
    try:
        selection_path = output / "selection.json"
        step = run(["java", "-cp", str(build), "BPSOTestSelector", str(CANDIDATES), str(selection_path),
                    str(seed), str(args.particles), str(args.iterations)], ROOT, output / "select.log", args.timeout)
        require(step, "Run selector")
        selection = json.loads(selection_path.read_text(encoding="utf-8"))
        selected = selection["selected_test_ids"]
        if not selected or not set(selected).issubset(ids):
            raise RuntimeError("Selector returned invalid candidate IDs")
        summary["selection"] = selection
        summary["buggy"] = execute_version(defects4j, "b", selected, args.work_root, output, args.timeout)
        summary["fixed"] = execute_version(defects4j, "f", selected, args.work_root, output, args.timeout)
        for buggy, fixed in zip(summary["buggy"]["tests"], summary["fixed"]["tests"]):
            buggy["detects_bug"] = (buggy["failing_tests"] is not None and fixed["failing_tests"] is not None
                                     and buggy["failing_tests"] > 0 and fixed["failing_tests"] == 0)
        summary["fault_detected"] = any(item["detects_bug"] for item in summary["buggy"]["tests"])
        summary["status"] = "verified"
    except Exception as exc:
        summary["status"] = "error"
        summary["error"] = str(exc)
    summary["finished_utc"] = now()
    write_json(summary_path, summary)
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rounds", type=int, default=2)
    parser.add_argument("--seed", type=int, default=20260928)
    parser.add_argument("--particles", type=int, default=30)
    parser.add_argument("--iterations", type=int, default=200)
    parser.add_argument("--timeout", type=int, default=900)
    parser.add_argument("--work-root", type=Path, default=ROOT / "projects")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    if args.rounds < 1 or args.particles < 1 or args.iterations < 0:
        parser.error("rounds and particles must be positive; iterations must be non-negative")
    ids = candidate_ids()
    if args.dry_run:
        print(json.dumps({"bug": "Chart-1", "rounds": args.rounds, "candidates": ids}, indent=2))
        return 0
    defects4j = shutil.which("defects4j")
    if not defects4j:
        parser.error("defects4j is not in PATH; run from Ubuntu/WSL with Defects4J installed")
    args.work_root = args.work_root.resolve()
    build = compile_selector(BPSO / ".build", args.timeout)
    summaries = [one_round(defects4j, build, args.seed + index, index + 1, args, ids)
                 for index in range(args.rounds)]
    statuses = [summary["status"] for summary in summaries]
    if all(status == "verified" for status in statuses):
        update_index("verified")
    print("; ".join(f"round {index + 1}: {status}" for index, status in enumerate(statuses)))
    return 0 if all(status == "verified" for status in statuses) else 1


if __name__ == "__main__":
    sys.exit(main())
